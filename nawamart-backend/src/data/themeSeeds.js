async function seedThemes() {
  const Theme = require('../models/Theme');
  const existing = await Theme.countDocuments();
  if (existing > 0) {
    console.log(`[ThemeSeed] ${existing} themes already exist, skipping seed.`);
    return;
  }
  await Theme.insertMany([defaultTheme, ...themes]);
  console.log(`[ThemeSeed] Seeded ${themes.length + 1} themes successfully.`);
}

